// Usage: npm run eval
// Compares verification/raw/<slug>.vN.json (generator output) with data/guides/<slug>.json (verified seed)
// and rewrites the generated table block in docs/EVAL.md. Text outside the markers is kept.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { compareGuides, type Comparison } from "../lib/eval/compare";
import { guideSchema, type Guide } from "../lib/guide/schema";

const START = "<!-- eval:start -->";
const END = "<!-- eval:end -->";
const load = (path: string): Guide => guideSchema.parse(JSON.parse(readFileSync(path, "utf8")));
const pct = (n: number, d: number): string => (d === 0 ? "n/a" : `${Math.round((100 * n) / d)}%`);
const frac = (x: { matched: number; total: number }): string => `${x.matched}/${x.total}`;
const yes = (b: boolean): string => (b ? "yes" : "**no**");

const byVersion = new Map<string, Comparison[]>();
for (const file of readdirSync("verification/raw").filter((f) => /\.v\d+\.json$/.test(f)).sort()) {
  const [, slug, version] = file.match(/^(.+)\.(v\d+)\.json$/) ?? [];
  if (!slug || !version || !existsSync(`data/guides/${slug}.json`)) continue;
  const list = byVersion.get(version) ?? [];
  list.push(compareGuides(load(`verification/raw/${file}`), load(`data/guides/${slug}.json`)));
  byVersion.set(version, list);
}

const lines: string[] = [START, "", `Generated by \`npm run eval\` on ${new Date().toISOString().slice(0, 10)}.`, ""];
for (const [version, rows] of [...byVersion.entries()].sort()) {
  const sum = (pick: (c: Comparison) => { matched: number; total: number }): string => {
    const m = rows.reduce((a, c) => a + pick(c).matched, 0);
    const t = rows.reduce((a, c) => a + pick(c).total, 0);
    return `${m}/${t} (${pct(m, t)})`;
  };
  lines.push(`### Prompt ${version} (${rows.length} apps)`, "");
  lines.push("| App | OAuth support | Tier (gen vs seed) | Off by one | Customer gate | Managed app | Stage review | Stage waits overlap | Scope review levels | Evidence with URL | Inferred |");
  lines.push("|---|---|---|---|---|---|---|---|---|---|---|");
  for (const c of rows) {
    lines.push(
      `| ${c.slug} | ${yes(c.oauthSupport)} | ${c.generatedTier} vs ${c.seedTier}${c.tierExact ? "" : " **x**"} | ${yes(c.tierOffByOne)} | ${yes(c.customerSideGate)} | ${yes(c.managedApp)} | ${frac(c.stageReview)} | ${frac(c.stageWaitOverlap)} | ${frac(c.scopeReviewLevels)} | ${pct(Math.round(c.evidenceWithUrl * 100), 100)} | ${c.inferredCount}/${c.evidenceCount} |`,
    );
  }
  const exact = rows.filter((c) => c.tierExact).length;
  lines.push(
    `| **Total** | ${rows.filter((c) => c.oauthSupport).length}/${rows.length} | ${exact}/${rows.length} exact | ${rows.filter((c) => c.tierOffByOne).length}/${rows.length} | ${rows.filter((c) => c.customerSideGate).length}/${rows.length} | ${rows.filter((c) => c.managedApp).length}/${rows.length} | ${sum((c) => c.stageReview)} | ${sum((c) => c.stageWaitOverlap)} | ${sum((c) => c.scopeReviewLevels)} | | |`,
    "",
  );
}
lines.push(END);

const path = "docs/EVAL.md";
const current = existsSync(path) ? readFileSync(path, "utf8") : `# Eval: generator vs verified seeds\n\n${START}\n${END}\n`;
const next = current.includes(START) ? current.replace(new RegExp(`${START}[\\s\\S]*${END}`), lines.join("\n")) : `${current}\n${lines.join("\n")}\n`;
writeFileSync(path, next);
console.log(lines.join("\n"));
